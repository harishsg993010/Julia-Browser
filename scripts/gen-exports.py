# Generate src/js/env/94_exports.js: the browser environment is evaluated inside one block
# (see BROWSER_ENV in src/js/mod.rs), so its top-level `class` and `function` declarations are
# block-scoped instead of global lexical bindings that page scripts could not replace (a page doing
# `window.HTMLElement = shim; HTMLElement.prototype = ...` must see its own shim, as in a browser).
# This file makes each of them a window property (writable, configurable, non-enumerable) unless
# the environment already put one there.
#   python scripts/gen-exports.py
import os, re, glob
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "js", "env")
names = []
for p in sorted(glob.glob(os.path.join(root, "*.js"))):
    base = os.path.basename(p)
    if base >= "94":
        continue
    if base == "67_editing.js":  # generated engine wrapped in a closure (and skipped in workers)
        continue
    for line in open(p, encoding="utf-8"):
        m = re.match(r"^(?:class|function)\s+([A-Za-z_$][\w$]*)", line)
        if m and m.group(1) not in names:
            names.append(m.group(1))
out = ["// Generated by scripts/gen-exports.py; do not edit.",
       "// Top-level classes and functions of the environment become window properties."]
out.append("(function (exp) {")
out.append("  exp.forEach(function (e) { if (!Object.prototype.hasOwnProperty.call(globalThis, e[0])) Object.defineProperty(globalThis, e[0], { value: e[1], writable: true, configurable: true, enumerable: false }); });")
out.append("})([")
out.append(",\n".join('  ["%s", %s]' % (n, n) for n in names))
out.append("]);")
open(os.path.join(root, "94_exports.js"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("exported", len(names))
