"""Generate src/js/env/67_editing.js from the web-platform-tests copy of Aryeh Gregor's reference
implementation of the HTML Editing APIs (execCommand) spec.

    py scripts/gen-editing.py [path/to/wpt]      (default: ../wpt)

The implementation is wrapped in a closure (its many helper names stay private: test pages load
their own copy as globals) and exported as `__jb.editing`; Document's execCommand/queryCommand*
methods (40_document.js / 67b_editing_glue.js) call into it. Small adaptations are applied as
exact-string patches below; each must match exactly once.
"""
import os
import sys

wpt = sys.argv[1] if len(sys.argv) > 1 else os.path.join("..", "wpt")
src_path = os.path.join(wpt, "editing", "include", "implementation.js")
src = open(src_path, encoding="utf-8").read()

# (old, new) adaptations of the reference implementation.
PATCHES = [
    # the file's own directive (the environment is strict already)
    ('"use strict";\n', ""),
    # contenteditable="plaintext-only" elements are editing hosts too (HTML: "plaintext-only state")
    ('''        && (node.contentEditable == "true"
        || (node.parentNode''',
     '''        && (node.contentEditable == "true" || node.contentEditable == "plaintext-only"
        || (node.parentNode'''),
]
for old, new in PATCHES:
    n = src.count(old)
    assert n == 1, (old[:60], n)
    src = src.replace(old, new)

out = []
out.append("// ---- HTML Editing APIs: execCommand / queryCommand* ----")
out.append("// GENERATED by scripts/gen-editing.py from web-platform-tests editing/include/implementation.js")
out.append("// (Aryeh Gregor's reference implementation of the editing spec; web-platform-tests, 3-Clause BSD")
out.append("// license). Do not edit by hand: change the generator's patches and regenerate.")
out.append("(function () {")
out.append("if (globalThis.__jb_workerRealm) return;")
out.append(src)
out.append("__jb.editing = {")
out.append("  exec: myExecCommand, enabled: myQueryCommandEnabled, indeterm: myQueryCommandIndeterm,")
out.append("  state: myQueryCommandState, supported: myQueryCommandSupported, value: myQueryCommandValue,")
out.append("  commands: commands, getActiveRange: getActiveRange, isEditingHost: isEditingHost, isEditable: isEditable,")
out.append("};")
out.append("})();")
dst = os.path.join("src", "js", "env", "67_editing.js")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", dst, len(src.splitlines()), "lines")
